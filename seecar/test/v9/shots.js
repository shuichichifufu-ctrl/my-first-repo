// v9 UI の見た目確認（全画面のスクリーンショット）: node shots.js [file] [tag] [WxH]
const { openPage } = require('../harness.js');
const path = require('path');
const FILE = process.argv[2] || path.join(__dirname, 'seecar_v9t.html');
const TAG = process.argv[3] || 'a';
const [VW, VH] = (process.argv[4] || '1280x720').split('x').map(Number);
const OUT = path.join(__dirname, '..', 'shots', 'v9');
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
(async () => {
  const { browser, page, errors } = await openPage(FILE, { viewport: { width: VW, height: VH } });
  const shot = async (n) => { await page.screenshot({ path: path.join(OUT, `${TAG}_${VW}x${VH}_${n}.png`) }); };
  const click = async (sel, ms = 350) => { await page.click(sel, { force: true }); await sleep(ms); };
  await sleep(300); await shot('01boot_loading');
  await sleep(1200); await shot('02boot_ready');
  await click('#bootbtn', 700); await shot('03title');
  await click('#home'); await shot('04modal_title'); await click('#m-no');
  await click('#nav [data-nav="せってい"]'); await shot('05settings');
  await click('.swatch[data-pal="3"]'); await click('.seg button[data-val="sonar"]'); await shot('06settings_changed');
  await click('#back'); await click('#nav [data-nav="はじめる"]'); await shot('07how');
  await click('.howcard[data-kind=count]'); await shot('08who');
  await click('[data-who=cpu]'); await shot('09level');
  await click('.lvcard[data-level=normal]'); await shot('10pick');
  await click('.card[data-id]', 1500); await shot('11pick_chosen');
  await click('#nav [data-nav="しゅっぱつ！"]', 600); await shot('12count_3');
  await sleep(1500); await shot('13count_1');
  await sleep(1300); await shot('14count_go');
  await sleep(1800); await shot('15play');
  await page.evaluate(() => App._onomato('jump')); await sleep(250);
  await page.evaluate(() => App._onomato('bump')); await sleep(200); await shot('16onomato');
  await sleep(1200);
  await page.evaluate(() => App._gemHit(0, 0)); await sleep(900); await shot('17announce_me');
  await sleep(3200);
  await page.evaluate(() => App._gemHit(1, 1)); await sleep(900); await shot('18announce_cpu');
  await click('#home'); await shot('19modal_play'); await click('#m-no');
  await sleep(3500);
  await page.evaluate(() => App._finish()); await sleep(1600); await shot('20ending');
  console.log(JSON.stringify(await page.evaluate(() => App._info())));
  await click('#home'); await shot('21modal_ending'); await click('#m-yes', 600); await shot('22title_again');
  await click('#home'); await click('#m-yes', 600); await shot('23quit');
  console.log(errors.join('\n'));
  await browser.close(); process.exit(0);
})();
